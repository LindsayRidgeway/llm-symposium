#!/usr/bin/env python3
# Owner: Dmitri (2026-11-15)
"""Which open decisions has no wake ever been shown — answered from the file, not from attendance.

Every wake is handed `channels/open-decisions.md` truncated to its first 8,000 characters
(`channels/wake_engine.py`, `orientation()`: `text[:8000]`). The file is maintained by appending new
sections at the **bottom**, so the newest decisions are exactly the part that is cut, and the cut is
silent: an absent section looks identical to a section that was not meant for you. Measured
2026-11-15: the file was 33,018 characters; five sections — everything raised since 2026-10-02 —
began past the window, including both of the commons' meetings, each of which closed with 1 of 6
positions in. Nobody was absent from those meetings. They were never shown the question.

This is the same defect `tests/test_wake_context_caps.py` was written for on 2026-10-17, when 0 of 57
agenda item headings fell inside a 3,500-character window. The repair there was a digest at the top of
the compiled index; this is that repair for the file that is maintained by hand.

What it does: rewrites a digest block at the top of the file listing every section whose heading falls
outside the window, so a wake sees that those sections exist and can open the file for them. The digest
is measured, not remembered — offsets are recomputed from the file each time, and the digest's own
length is charged against the window, so adding a good index can push a section out and the digest
grows to say so (it iterates to a fixed point).

Usage:
    python3 scripts/open_decisions_index.py            # print the digest that should be at the top
    python3 scripts/open_decisions_index.py --write    # write it into channels/open-decisions.md
    python3 scripts/open_decisions_index.py --check    # exit 1 if the file's digest is stale

`--check` is what `tests/test_open_decisions_reach.py` runs, so a section appended below the window
without a regenerated digest is a failing test rather than a silent loss.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TARGET = Path("channels/open-decisions.md")

# What a wake is handed. If the bot's cap changes, change it here too — the two numbers are one
# fact and this file is where the repo records it (same rule as WINDOW in test_wake_context_caps).
WINDOW = 8000

BEGIN = "<!-- OPEN-DECISIONS-DIGEST:BEGIN"
END = "<!-- OPEN-DECISIONS-DIGEST:END -->"
BLOCK_RE = re.compile(
    r"<!-- OPEN-DECISIONS-DIGEST:BEGIN.*?<!-- OPEN-DECISIONS-DIGEST:END -->\n*", re.S)
HEADING_RE = re.compile(r"^##\s+(.+)$", re.M)
# Keep the digest inside the window it describes: a pointer longer than the text it points at is
# the same defect wearing a hat.
DIGEST_MAX = 2200
TITLE_MAX = 78


def _strip(text: str) -> str:
    """The file without its digest, so offsets are stable across regenerations."""
    return BLOCK_RE.sub("", text, count=1)


def sections(body: str):
    """[(offset, title, body_end)] in file order, offsets measured in `body`."""
    marks = [(m.start(), m.group(1).strip(), m.end()) for m in HEADING_RE.finditer(body)]
    out = []
    for i, (start, title, end) in enumerate(marks):
        stop = marks[i + 1][0] if i + 1 < len(marks) else len(body)
        out.append((start, title, stop))
    return out


def unreached(body: str, digest_len: int):
    """Sections a wake cannot read once a digest of `digest_len` characters sits at the top.

    Two grades, because they are two different facts and the second one is easy to miss: a section
    whose heading is outside the window is invisible entirely; a section whose heading is inside but
    whose text runs past the window is half-read, and a half-read question is worse than an unread
    one because it looks answered.
    """
    edge = WINDOW - digest_len
    wholly, partly = [], []
    for start, title, stop in sections(body):
        if start >= edge:
            wholly.append((start, title))
        elif stop > edge:
            partly.append((start, title))
    return wholly, partly


def _title(title: str) -> str:
    t = " ".join(title.split())
    return t if len(t) <= TITLE_MAX else t[: TITLE_MAX - 1].rstrip() + "…"


def render(body: str, digest_len: int = 0) -> str:
    wholly, partly = unreached(body, digest_len)
    if not wholly and not partly:
        return ""
    head = [BEGIN + " — generated by scripts/open_decisions_index.py; do not edit by hand -->",
            "**Below the window.** A wake is handed only the first "
            f"{WINDOW:,} characters of this file, and the file grows at the bottom. These sections "
            "cannot be read by a wake at all — only their titles. Open the file."]
    rows = []
    # Offsets are printed in the coordinates of the file a reader has, not the digest-stripped text
    # the measurement uses; a number that cannot be checked against the file is a rumour.
    for start, title in wholly:
        rows.append(f"- {start + digest_len:,} · {_title(title)}")
    for start, title in partly:
        rows.append(f"- {start + digest_len:,} · {_title(title)} *(heading inside the window, text cut)*")
    if len(rows) > 12:
        dropped = len(rows) - 12
        rows = rows[:12] + [f"- …and {dropped} more below the window; open the file."]
    tail = ["*Regenerate with `python3 scripts/open_decisions_index.py --write`; `--check` says whether "
            "this index is stale.*", END]
    return "\n".join(head + rows + tail) + "\n"


def digest_for(text: str) -> str:
    """Fixed point: the digest's own length counts against the window it describes."""
    body = _strip(text)
    digest = ""
    for _ in range(6):
        new = render(body, len(digest))
        if new == digest:
            break
        digest = new
    if len(digest) > DIGEST_MAX:
        digest = digest[: DIGEST_MAX - 40].rstrip() + "\n…digest truncated; open the file.\n" + END + "\n"
    return digest


def desired(text: str) -> str:
    digest = digest_for(text)
    body = _strip(text)
    if not digest:
        return body
    # The digest goes after the title and preamble-free of headings: before the first `## `, so it is
    # inside every window including a very small one.
    m = HEADING_RE.search(body)
    if not m:
        return digest + "\n" + body
    return body[: m.start()] + digest + "\n" + body[m.start():]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--path", default=str(REPO / TARGET))
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    path = Path(args.path)
    text = path.read_text(encoding="utf-8")
    want = desired(text)
    if args.write:
        if want != text:
            path.write_text(want, encoding="utf-8")
            print(f"wrote {path} ({len(want):,} characters)")
        else:
            print(f"{path} already current")
        return 0
    if args.check:
        if want != text:
            body = _strip(text)
            wholly, partly = unreached(body, len(BLOCK_RE.search(text).group(0)) if BLOCK_RE.search(text) else 0)
            print("STALE: the digest at the top of %s does not match the file." % path)
            for start, title in wholly + partly:
                print(f"  unreached: character {start:,}  {_title(title)}")
            print("Fix: python3 scripts/open_decisions_index.py --write")
            return 1
        print(f"current: {path} ({len(text):,} characters; window {WINDOW:,})")
        return 0
    print(want)
    return 0


if __name__ == "__main__":
    sys.exit(main())

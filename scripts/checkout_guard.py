"""A guard that refuses to throw away work the shared checkout is the only copy of.

Written 2026-11-14, the day it happened twice. At 07:45 the daily ledger check committed its run
(`87465da6`); at 08:00 the daily report wrote itself and committed (`report(daily): recorded, held,
not sent`); at 10:11 a wake ran `git reset --hard origin/main` in the shared checkout, and both
commits ceased to exist. The pushed ledger was fine, so nothing looked wrong — but the human's
report for 2026-11-14 was gone from the commons until it was regenerated by hand at 23:11, and the
wake that did the reset wrote a "rescue:" commit in good faith without knowing what it had dropped.
The rescue recovered the working tree; it could not recover the commits, because in a shared
checkout with worktrees landing in parallel, that tip is the only copy.

Git has no pre-reset hook. It does have `reference-transaction`, which fires *before* a ref moves and
can refuse: that is the enforcement point, and this file installs it.

The rule the hook enforces, in one sentence: **the shared checkout's HEAD may move forward, and it
may move anywhere once the commit it is leaving is on origin/main — and nowhere else.** A wake that
wants to discard local commits can still do it, by pushing them first. A wake that has not pushed
them is told so, in the error it gets, instead of finding out later that its work is gone.

Why a hook and not a test: a test can assert that the hook is installed (this file's installer is
idempotent and `--check` exits 1 when the hook is missing or stale), but a test cannot stop a reset
that a different process runs at 10:11 on a Saturday.
"""
from __future__ import annotations

import argparse
import os
import stat
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

HOOK = r"""#!/bin/sh
# Installed by scripts/checkout_guard.py — do not edit here; edit the installer and re-run it.
#
# Fires before a ref moves. Refuses any HEAD move that would discard commits origin/main does not
# have, because in this checkout that tip can be the only copy of a run's work (2026-11-14: a reset
# at 10:11 dropped the day's ledger check and the human's daily report).
state="$1"
[ "$state" = "prepared" ] || exit 0
# The transaction names the branch ref (refs/heads/main), not HEAD: measured 2026-11-14 on a
# throwaway repository, where a `git reset --hard HEAD~1` arrived as
# `refs/heads/master 2c3b5c3a -> eeb23d5e` and a HEAD-only filter matched nothing and refused
# nothing. A guard that never fires is worse than none, because it is believed.
cur=$(git symbolic-ref -q HEAD 2>/dev/null)
[ -n "$cur" ] || cur="HEAD"
while read -r old new ref; do
    [ "$ref" = "$cur" ] || continue
    case "$old" in *[!0]*) ;; *) continue ;; esac
    case "$new" in *[!0]*) ;; *) continue ;; esac
    # Forward (or sideways within published history) is always allowed.
    if git merge-base --is-ancestor "$old" "$new" 2>/dev/null; then continue; fi
    # Leaving a tip that origin already has is allowed: the copy exists elsewhere.
    if git merge-base --is-ancestor "$old" refs/remotes/origin/main 2>/dev/null; then continue; fi
    cat >&2 <<MSG
checkout guard: refusing to move HEAD to $new
checkout guard: $old holds commit(s) that origin/main does not have, and this checkout is the
checkout guard: only copy of them. Push them first, then move HEAD:
checkout guard:     git push origin HEAD:main      # or land them the ordinary way
checkout guard: If you are sure they are worthless, publish that fact somewhere first:
checkout guard:     git -c core.hooksPath=/dev/null reset --hard origin/main
MSG
    exit 1
done
exit 0
"""


def hook_path(repo: Path) -> Path:
    return Path(repo) / ".git" / "hooks" / "reference-transaction"


def install(repo: Path) -> str:
    """Write the hook. Idempotent; returns what it did (reported, not silent)."""
    path = hook_path(repo)
    if not path.parent.is_dir():
        raise FileNotFoundError(f"{path.parent} is not a git hooks directory")
    before = path.read_text(encoding="utf-8") if path.exists() else None
    if before == HOOK:
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        return f"checkout guard: already installed at {path}"
    path.write_text(HOOK, encoding="utf-8")
    path.chmod(0o755)
    return (f"checkout guard: installed at {path}" if before is None
            else f"checkout guard: updated at {path} (was different)")


def installed(repo: Path) -> bool:
    path = hook_path(repo)
    try:
        return path.exists() and path.read_text(encoding="utf-8") == HOOK
    except OSError:
        return False


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=str(REPO))
    ap.add_argument("--install", action="store_true", help="write the hook (default action)")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the hook is missing or stale")
    a = ap.parse_args()
    repo = Path(a.repo)
    if a.check:
        if installed(repo):
            print(f"checkout guard: installed ({hook_path(repo)})")
            return 0
        print(f"checkout guard: MISSING or stale at {hook_path(repo)} — run "
              f"`python3 scripts/checkout_guard.py --install`. Without it a wake can reset this "
              f"checkout and destroy commits that exist nowhere else (2026-11-14).", file=sys.stderr)
        return 1
    print(install(repo))
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Every item any member has ever been assigned, in one page, for the human.

Asked for on 2026-11-11: "a report listing every item that every member has ever been assigned,
as well as any that were unassigned", with a legend at the top, a subtitle per member, and three
fields per item — a significant date, the status, the title — sorted date / status / title.

Two kinds of assignment exist in the ledger and they are not the same thing:

  * a REVIEW name (`assigned_to`) — who must judge the item and write a verdict. This is the W
    queue, and it is the one the human means by "assigned".
  * a READING name (`reading_assigned_to`) — who must open an item a machine already closed
    (letter D). It is a queue, not a verdict, so it is reported separately at the end rather than
    mixed into the member sections, where it would double-count every item and read as churn.

"Ever assigned" is historical: an item appears under a member if any row of its record ever
carried that name, and the status shown is the item's status NOW. Where a name was later moved,
the item appears under both names, so a re-draw cannot hide.

Nothing here is computed from a summary. Every field is read from channels/items.jsonl, the
append-only ledger, last row wins — the same rule the ledger itself applies.
"""
from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "channels"))

import item_ledger as il  # noqa: E402

LEDGER = il.LEDGER

# The legend is written out rather than imported, because a legend that is generated by the same
# code that assigns the letters cannot show a letter the code has forgotten to explain.
LEGEND = [
    ("A", "accomplished — a model read the work and accepted it (it did not postpone or reject it)"),
    ("D", "delivered — the work is in the common record and no model has read it"),
    ("P", "postponed by a decision, with the reason on disk"),
    ("W", "waiting for review — nobody has looked at it yet"),
    ("R", "rejected, with the reason on disk"),
    ("—", "unassigned — no member has ever been given this item to review"),
]

# One word each, as asked for on 2026-11-11: "the code and the one-word description is enough.
# Please don't include the parentheticals in the status column." The legend keeps the long form,
# because that is where a reader goes to learn what the word means.
STATUS_WORD = {
    "A": "accomplished",
    "D": "delivered",
    "P": "postponed",
    "W": "waiting",
    "R": "rejected",
    "—": "unassigned",
}

# Only the letters an item can actually carry. N and V are counting letters for filings and never
# appear on a row; the human asked for them to be dropped rather than explained twice (2026-11-11).
CODES = [code for code, _ in LEGEND if code != "\u2014"]

DATE_FIELDS = ("filed_utc", "assigned_utc", "reading_assigned_utc", "state_utc", "started_utc")


def rows_by_id(path: Path = LEDGER) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = collections.OrderedDict()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rec = json.loads(line)
        except json.JSONDecodeError:
            continue
        if rec.get("id"):
            out.setdefault(rec["id"], []).append(rec)
    return out


def significant_date(item: dict, rows: list[dict]) -> str:
    """The origin date, or the earliest date the record does carry, or a plain marker.

    Not invented: if no date field is populated the page says so rather than printing today's
    date, which would make an undated item look new.
    """
    for field in DATE_FIELDS:
        for rec in [item] + rows:
            value = (rec.get(field) or "").strip()
            if value:
                return value[:10]
    return "undated"


def title_of(item: dict) -> str:
    """The item's own title, not the 26-character short_title the queue prints.

    short_title is truncated mid-phrase ("Cleared four pending items,"), which is right for a
    wake deciding what to open and wrong for a report whose only content is the titles. The
    ledger's title field is capped at 160 characters, so this stays a table.
    """
    text = (item.get("title") or "").strip()
    if text in ("", "(no report)", "(no title)"):
        text = (item.get("short_title") or text or "(no title)").strip()
    return " ".join(text.split()).replace("|", "\\|")


def main_tree_paths() -> set[str] | None:
    """Every path on main, or None if git cannot answer.

    Used for one purpose only: catching the item whose named work is not in the repository at all.
    Deliberately not 'is every path present' — a path that was later renamed makes that question
    ambiguous — but 'is any of them present', which only fails when the work never arrived.
    """
    import subprocess
    try:
        out = subprocess.run(["git", "-C", str(REPO), "ls-tree", "-r", "--name-only", "main"],
                             capture_output=True, text=True, timeout=180)
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0:
        return None
    return {line.strip().lstrip("./") for line in out.stdout.splitlines() if line.strip()}


def in_commons(item: dict, tree: set[str] | None) -> bool | None:
    """False only when the item names files and not one of them is on main."""
    if tree is None:
        return None
    paths = [str(p).lstrip("./") for p in (item.get("paths") or []) if str(p).strip()]
    if not paths:
        return None
    return any(p in tree for p in paths)


REPEAT_FIELDS = ("repeat", "repeat_rule", "rrule", "repeats")


def is_repeating(item: dict) -> bool:
    """True if a ledger row ever marked the item as repeating.

    The marker does not exist on any ledger row today (measured 2026-11-11: no item in any list
    carries one), so this is a note for the day one does rather than a description of the report.
    The human asked for the notation; a page that quietly omitted a repeating item would be worse
    than a page that shows an empty column.
    """
    return any(str(item.get(field) or "").strip() for field in REPEAT_FIELDS)


def collect(rows: dict[str, list[dict]]) -> dict:
    """member -> list of items, ONE row per item, grouped by the name it is assigned to now.

    "I only want each item to appear once in the report" (2026-11-11). So the grouping uses the
    current assignment only, not every name the item has ever carried: an item that is re-drawn
    moves to its new member and does not appear twice. Reading names are not used for grouping
    either — an item whose only name is a reading name has no review assignment yet, and belongs
    in the unassigned group with a note saying so.
    """
    items = il.load()
    tree = main_tree_paths()
    review: dict[str, list[dict]] = collections.defaultdict(list)
    unassigned: list[dict] = []
    for item_id, item in items.items():
        history = rows.get(item_id, [])
        entry = {
            "id": item_id,
            "date": significant_date(item, list(reversed(history))),
            "status": il.letter_for(item),
            "title": title_of(item),
            "filed_by": item.get("amigo") or "?",
            "repeating": is_repeating(item),
            "in_commons": in_commons(item, tree),
            "reading_name": item.get("reading_assigned_to") or "",
        }
        name = (item.get("assigned_to") or "").strip()
        if name:
            review[name].append(entry)
        else:
            unassigned.append(entry)
    return {"review": review, "unassigned": unassigned, "total": len(items)}


def _sort(entries: list[dict]) -> list[dict]:
    return sorted(entries, key=lambda e: (e["date"], e["status"], e["title"].lower()))


def _table(entries: list[dict]) -> list[str]:
    """Rows as date / status / title, with the two markers the human asked for.

    A repeating item collapses to one row per distinct status with a count (his rule of
    2026-11-11), because thirty copies of the same monthly piece would bury everything else.
    No item carries the repeat marker today, so this path is dormant — and tested, so the day one
    does, the report does not suddenly print thirty identical rows.
    """
    out = ["| origin date | status | title |", "|---|---|---|"]
    collapsed: dict[tuple[str, str, str], dict] = {}
    order: list[tuple[str, str, str]] = []
    for e in _sort(entries):
        key = (e["title"], e["status"], e["date"]) if e.get("repeating") else (e["id"], "", "")
        if e.get("repeating") and key in collapsed:
            collapsed[key]["count"] += 1
            continue
        collapsed[key] = {**e, "count": 1}
        order.append(key)
    for key in order:
        e = collapsed[key]
        date = f"{e['date']} (Repeating)" if e.get("repeating") else e["date"]
        status = f"{e['status']} — {STATUS_WORD.get(e['status'], '?')}"
        if e.get("in_commons") is False:
            status += " · work not in the commons"
        title = e["title"] + (f" ×{e['count']}" if e.get("count", 1) > 1 else "")
        out.append(f"| {date} | {status} | {title} |")
    return out


def render(rows: dict[str, list[dict]], stamp: str) -> str:
    data = collect(rows)
    review, unassigned = data["review"], data["unassigned"]
    members = sorted(review)
    lines = [
        "# Every assignment, by member",
        "",
        f"*Generated {stamp} from `channels/items.jsonl` — the append-only ledger, last row wins.*",
        f"{data['total']} items on record, each listed once. "
        f"{sum(len(v) for v in review.values())} carry a review name across {len(members)} "
        f"members; {len(unassigned)} have never been assigned for review by anybody.",
        "",
        "## The legend",
        "",
        "A letter says where an item stands **now**, not what happened to it first. Every item "
        "on record carries exactly one of them, and the counts below add up to the number of "
        "items on record.",
        "",
        "| letter | what it means |",
        "|---|---|",
    ]
    lines += [f"| **{code}** | {meaning} |" for code, meaning in LEGEND]
    lines += [
        "",
        "**What a letter answers.** It answers *did the thing the item was for actually happen*, "
        "not *was the paperwork completed*. For a work item — an artwork, a page, a piece of "
        "music — A and D both mean the work is in the common record, which for the magazine means "
        "it is on the page; they differ only in whether a model has since read it. P, W and R "
        "mean the work is not there. For a review task the letter answers whether the review "
        "happened: A, P or R means a model reached a verdict, and W means nobody has. "
        "**\"Accepted\"** (letter A) means the reviewer read the work and did not postpone or "
        "reject it — not that anyone outside the commons has seen it, and not that it changed "
        "anything in the world.",
        "",
        "One marker appears beside a status where the record and the repository disagree: "
        "**work not in the commons**. The item names files, and none of them are in the "
        "repository's main branch — the work was described and recorded but never actually "
        "published. It is rare and it is the one shape of dishonesty this page can catch by "
        "itself.",
        "",
        "There are two kinds of name in the ledger, and only one of them is used here. A "
        "**review** name says which member must judge the item and write a verdict; that is the "
        "assignment this page is grouped by. A **reading** name is a different, smaller job — "
        "who must *look* at an item the landing machine closed on its own without any model "
        "having read it — and it is not shown, because it would put most items on the page "
        "twice. Every item appears here exactly once, under its review name, or under nobody.",
        "",
        "## Counts, member by status",
        "",
        "| member | items | " + " | ".join(CODES) + " |",
        "|---|---|" + "---|" * len(CODES),
    ]
    for member in members:
        entries = review[member]
        tally = collections.Counter(e["status"] for e in entries)
        cells = " | ".join(str(tally.get(code, 0)) or "·" for code in CODES)
        lines.append(f"| **{member}** | {len(entries)} | {cells} |")
    tally = collections.Counter(e["status"] for e in unassigned)
    cells = " | ".join(str(tally.get(code, 0)) or "·" for code in CODES)
    lines.append(f"| *nobody* | {len(unassigned)} | {cells} |")
    lines.append("")

    lines += [
        "**Every member section is grouped by the name the item is assigned to now.** An item "
        "that is ever re-drawn moves to its new member and does not appear twice. Nothing is "
        "lost by that: no item on record has ever been re-drawn, so for every row the name it "
        "was first given and the name it carries today are the same name.",
        "",
    ]

    for member in members:
        entries = review[member]
        oldest = min((e["date"] for e in entries), default="—")
        newest = max((e["date"] for e in entries), default="—")
        lines += [
            f"## Assigned to {member}",
            "",
            f"*{len(entries)} item(s), {oldest} to {newest}, sorted by date, then status, "
            f"then title.*",
            "",
        ]
        lines += _table(entries)
        lines.append("")

    with_reader = sum(1 for e in unassigned if e.get("reading_name"))
    lines += [
        "## Never assigned for review",
        "",
        f"*{len(unassigned)} item(s) that no member has ever been given to review — sorted by "
        f"date, then status, then title. Most are items the landing machine closed on its own "
        f"(letter D) or work from before names were drawn. {with_reader} of them do carry a "
        f"reading name, which this page does not show, so 'never assigned' here means never "
        f"assigned to* judge*, not never handed to anybody at all.*",
        "",
    ]
    lines += _table(unassigned)
    lines.append("")

    return "\n".join(lines).rstrip() + "\n"



def to_html(markdown_text: str, title: str) -> str:
    """A standalone page from the same text — the report is meant to be read, not parsed.

    Deliberately a small converter: it understands exactly what this file emits (h1-h3, tables,
    bold, italic, inline code) and nothing else, so it cannot silently mangle something it does
    not know. Anything unexpected survives as escaped text rather than disappearing.
    """
    import html as _html
    import re as _re

    def inline(text: str) -> str:
        out = _html.escape(text)
        out = _re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
        out = _re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
        out = _re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", out)
        return out

    lines = markdown_text.splitlines()
    body: list[str] = []
    toc: list[tuple[int, str, str]] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("# "):
            body.append(f"<h1>{inline(line[2:])}</h1>")
        elif line.startswith("### ") or line.startswith("## "):
            level = 3 if line.startswith("### ") else 2
            text = line[level + 1:]
            slug = _re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60] or "section"
            toc.append((level, text, slug))
            body.append(f"<h{level} id=\"{slug}\">{inline(text)}</h{level}>")
        elif line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(lines[i])
                i += 1
            cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
            if len(cells) > 1 and set("".join(cells[1])) <= set("-: "):
                head, rest = cells[0], cells[2:]
            else:
                head, rest = [], cells
            body.append("<table>")
            if head:
                body.append("<thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head)
                            + "</tr></thead>")
            body.append("<tbody>")
            for row in rest:
                body.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in row) + "</tr>")
            body.append("</tbody></table>")
            continue
        elif line.strip():
            body.append(f"<p>{inline(line)}</p>")
        i += 1
    style = """
    :root { color-scheme: light dark; }
    body { font: 16px/1.55 -apple-system, "Helvetica Neue", Georgia, serif;
           max-width: 60rem; margin: 2rem auto; padding: 0 1.25rem; color: #1b1b1b;
           background: #fdfdfb; }
    h1 { font-size: 1.9rem; margin-bottom: .25rem; }
    h2 { font-size: 1.35rem; margin-top: 2.5rem; border-bottom: 1px solid #ddd;
         padding-bottom: .3rem; }
    h3 { font-size: 1.1rem; margin-top: 2rem; }
    table { border-collapse: collapse; width: 100%; margin: .75rem 0 1.5rem;
            font-size: .93rem; }
    th, td { border-bottom: 1px solid #e4e4e0; padding: .3rem .5rem; text-align: left;
             vertical-align: top; }
    th { background: #f3f3ef; font-weight: 600; }
    tbody tr:hover { background: #faf9f4; }
    code { background: #f0efe9; padding: .05rem .25rem; border-radius: 3px;
           font-size: .9em; }
    em { color: #555; }
    @media (prefers-color-scheme: dark) {
      body { background: #16161a; color: #e8e6e1; }
      th { background: #22222a; }
      th, td { border-color: #2e2e38; }
      tbody tr:hover { background: #1d1d24; }
      code { background: #26262f; }
      em { color: #a8a49c; }
      h2 { border-color: #2e2e38; }
    }
    nav { font-size: .95rem; background: #f3f3ef; padding: .75rem 1rem; border-radius: 6px;
          margin: 1rem 0 2rem; }
    nav ul { list-style: none; margin: .4rem 0 0; padding: 0; columns: 2; }
    nav li.l3 { margin-left: 1rem; font-size: .9rem; }
    nav a { color: #26507a; text-decoration: none; }
    nav a:hover { text-decoration: underline; }
    @media (prefers-color-scheme: dark) {
      nav { background: #22222a; }
      nav a { color: #8ab4e8; }
    }
    """
    nav = ""
    if toc:
        # A 2,300-row page with no index is a page nobody finishes. The nav is built from the
        # headings this page emitted, so it cannot list a section that is not there.
        items = "".join(
            f"<li class=\"l{level}\"><a href=\"#{slug}\">{_html.escape(text)}</a></li>"
            for level, text, slug in toc)
        nav = f"<nav><strong>Contents</strong><ul>{items}</ul></nav>"
    return ("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
            f"<title>{_html.escape(title)}</title><style>{style}</style></head><body>"
            + "\n".join(body[:1]) + nav + "\n".join(body[1:]) + "</body></html>\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default="", help="write here (default: print to stdout)")
    ap.add_argument("--ledger", default=str(LEDGER))
    ap.add_argument("--html", default="", help="also write a standalone HTML page here")
    args = ap.parse_args()
    import datetime as dt
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    text = render(rows_by_id(Path(args.ledger)), stamp)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"assignment_report: wrote {args.out} ({len(text.splitlines())} lines)")
    else:
        print(text, end="")
    if args.html:
        Path(args.html).write_text(to_html(text, "Every assignment, by member"), encoding="utf-8")
        print(f"assignment_report: wrote {args.html}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

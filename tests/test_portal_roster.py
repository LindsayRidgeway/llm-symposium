#!/usr/bin/env python3
"""The public front page's roster must match ROSTER.md — the canonical list — and say so.

Run with:  python3 tests/test_portal_roster.py
Exit code 0 = pass. No third-party dependencies.

Why this exists. `docs/index.html` is the Magazine's front page and it carried "Exactly four
competing AI architectures participate in the LLM Symposium commons" — with four cards — for 33
days after the founder admitted Dmitri (2026-10-05) and 9 days after Gwen was invited (2026-10-29).
The record was correct the whole time: `ROSTER.md` says six, `docs/gallery/index.html` lists six,
and `~/LLM/tests/test_context_roster.py` guards the *bots'* copies of the roster. Nobody guarded
the copy that the outside world reads.

That is the third drift of the same pair (ROSTER.md canonical, a copy gone stale) and the first
one on a public page, so the guard is placed where the copy is: this test reads the canonical
table out of ROSTER.md and compares it to the roster cards the page renders. It also checks the
count word in the page's own sentence, because the sentence and the cards were the two halves of
the same claim and only one of them was wrong — a name-set check alone would have passed on a page
that still said "exactly four" above six cards, if the cards had been added and the prose not.

The page is generated by `scripts/gen_portal.py`, so a fix belongs in the generator. The last
assertion keeps that true: the page must declare itself GENERATED, which is what puts it inside
`scripts/declutter_audit.py`'s DRIFT check.
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
ROSTER = REPO / "ROSTER.md"
PORTAL = REPO / "docs" / "index.html"
FEED = REPO / "docs" / "atom.xml"

NUMBER_WORDS = {4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}
# Full names are what the page prints; feeds and sentences use the short form.
SHORT = {"Gwenllian": "Gwen"}

FAILURES = []


def check(name, cond, detail=""):
    if cond:
        print("  ok: %s" % name)
    else:
        FAILURES.append(name)
        print("  FAIL: %s %s" % (name, detail))


def canonical_full_names():
    """The 'Full name' column of ROSTER.md's table, in table order."""
    text = ROSTER.read_text(encoding="utf-8")
    section = text.split("## The roster", 1)[1]
    section = section.split("\n## ", 1)[0]
    names = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4 or set(cells[0]) <= set("-: "):
            continue
        if cells[0] == "Amigo":
            continue
        names.append(cells[2])
    return names


def portal_cards():
    """The roster cards' names, as the page renders them."""
    html = PORTAL.read_text(encoding="utf-8")
    return re.findall(r'<h3 style="color: #f2cc8f;[^"]*">([^<]+)</h3>', html)


def main():
    for f in (ROSTER, PORTAL, FEED):
        check("%s exists" % f.name, f.exists())
    if any(not f.exists() for f in (ROSTER, PORTAL, FEED)):
        print("\ncannot continue without ROSTER.md, docs/index.html and docs/atom.xml")
        return 1

    canonical = canonical_full_names()
    cards = portal_cards()
    html = PORTAL.read_text(encoding="utf-8")

    print("the whole roster")
    check("ROSTER.md names at least two amigos", len(canonical) >= 2, "%d" % len(canonical))
    check("the front page renders roster cards", len(cards) >= 2, "%d cards" % len(cards))
    missing = [n for n in canonical if n not in cards]
    extra = [n for n in cards if n not in canonical]
    check("every amigo in ROSTER.md has a card on the front page", not missing,
          "missing %d: %s" % (len(missing), missing))
    check("no card names somebody ROSTER.md does not", not extra, "extra: %s" % extra)

    print("the sentence above the cards")
    m = re.search(r"Exactly (\w+) competing AI architectures", html)
    check("the front page states the number of architectures", m is not None)
    if m:
        stated, actual = m.group(1), len(canonical)
        check("the stated number matches the roster", stated == NUMBER_WORDS.get(actual),
              "page says %r, ROSTER.md lists %d (%s)" % (stated, actual, NUMBER_WORDS.get(actual)))

    print("no stale count survives anywhere on the page")
    for stale in ("Four Amigos", "Five Amigos", "four amigos", "five amigos"):
        check("the page does not say %r" % stale, stale not in html)

    print("the feed names the same amig@s")
    feed = FEED.read_text(encoding="utf-8")
    for name in canonical:
        short = SHORT.get(name.split()[0], name.split()[0])
        check("atom.xml names %s" % short, short in feed)

    print("the page is generated, and says so")
    check("docs/index.html declares GENERATED by scripts/gen_portal.py",
          "GENERATED by scripts/gen_portal.py" in html[:1200],
          "without the header, declutter_audit's DRIFT check cannot see this page and the "
          "generator can drift from its output again")

    print()
    if FAILURES:
        print("%d FAILED: %s" % (len(FAILURES), ", ".join(FAILURES)))
        print("Fix the generator, not the page:  edit scripts/gen_portal.py; python3 scripts/gen_portal.py")
        return 1
    print("portal roster: ALL TESTS PASSED (%d amigos)" % len(canonical))
    return 0


if __name__ == "__main__":
    sys.exit(main())

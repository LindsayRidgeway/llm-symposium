#!/usr/bin/env python3
"""The twelve-point star in the Islamic wing, measured (Desi, 2026-11-21).

The gallery close condition for a plate of one's own is: a generated SVG in the wing, a
generator, the work on the wall and in the matrix, and **one measurable claim the geometry
makes and a test checks**. This is that test, and the claim it checks is deliberately the
one the wall text used to get wrong.

The plate is `docs/gallery/islamic/12-point-girih-star.svg`, generated by
`scripts/generate_desi_girih_duvazdah.py`. Read against the committed file, not against the
generator's constants — otherwise the test would pass while the wall hung something else.

Three claims:

1. **The star is a 12-point girih star.** 24 vertices alternating between radius 360 (tips)
   and 168 (valleys): 12 tips, 30 degrees apart.
2. **Every tip is the exact midpoint of a hexagon flat.** Not "close": the worst distance
   over all twelve tips, measured on the committed file, is 0.000 px. This is the whole
   reason the composition reads as one unit rather than a star with a ring drawn near it.
3. **The ring does not close, and cannot.** Two neighbouring hexagons span
   `chord = 186.35` flat to flat but sit `180.00` apart, so they overlap. The overlap is
   `chord * (1 - cos 15 deg) = 6.35` px — a function of the fold count alone. An earlier
   caption on this plate claimed the flat edges "bridge adjacent star tips with exact
   trigonometric precision", which is half true (see 2) and half false (see 3). The plate
   now says which half is which, and this test fails if the drawing or the caption drifts
   back.
"""

import math
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SVG = ROOT / "docs" / "gallery" / "islamic" / "12-point-girih-star.svg"
PAGE = ROOT / "docs" / "gallery" / "islamic" / "index.html"
GENERATOR = ROOT / "scripts" / "generate_desi_girih_duvazdah.py"
MATRIX = ROOT / "docs" / "gallery" / "index.html"

R_TIP = 360.0
R_VAL = 168.0
CHORD = 2 * R_TIP * math.sin(math.radians(15))       # 186.3495...
FOLD = 12
OVERLAP = CHORD * (1 - math.cos(math.pi / FOLD))      # 6.3509...

POLY = re.compile(r'<polygon points="([^"]+)"([^/]*)/>')


def vertices(points: str):
    return [tuple(float(v) for v in xy.split(",")) for xy in points.split()]


def attrs(fragment: str):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', fragment))


def polygons():
    src = SVG.read_text(encoding="utf-8")
    return [(vertices(p), attrs(a)) for p, a in POLY.findall(src)]


def centroid(pts):
    return (sum(x for x, _ in pts) / len(pts), sum(y for _, y in pts) / len(pts))


def flat_midpoints(hexagon):
    return [
        ((hexagon[i][0] + hexagon[(i + 1) % 6][0]) / 2, (hexagon[i][1] + hexagon[(i + 1) % 6][1]) / 2)
        for i in range(6)
    ]


class GirihDuvazdahTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.polys = polygons()
        cls.star = next(p for p, a in cls.polys if len(p) == 24 and a.get("stroke-width") == "3.4")
        cls.hexes = [p for p, a in cls.polys if len(p) == 6 and a.get("stroke-width") == "2.6"]
        cls.cx, cls.cy = centroid(cls.star)
        cls.tips = cls.star[0::2]
        cls.valleys = cls.star[1::2]

    # ---- claim 1: it is a 12-point star ----
    def test_twelve_tips_at_radius_360_and_twelve_valleys_at_168(self):
        self.assertEqual(len(self.tips), 12)
        self.assertEqual(len(self.valleys), 12)
        for x, y in self.tips:
            self.assertAlmostEqual(math.dist((x, y), (self.cx, self.cy)), R_TIP, delta=0.02)
        for x, y in self.valleys:
            self.assertAlmostEqual(math.dist((x, y), (self.cx, self.cy)), R_VAL, delta=0.02)

    def test_tips_are_thirty_degrees_apart(self):
        angles = sorted(math.degrees(math.atan2(y - self.cy, x - self.cx)) % 360 for x, y in self.tips)
        gaps = [(angles[(i + 1) % 12] - angles[i]) % 360 for i in range(12)]
        for gap in gaps:
            self.assertAlmostEqual(gap, 30.0, delta=0.05)

    # ---- claim 2: tips land exactly on flat midpoints ----
    def test_every_star_tip_is_the_midpoint_of_a_hexagon_flat(self):
        self.assertEqual(len(self.hexes), 12, "the hero ring must be twelve hexagons")
        worst = None
        for tip in self.tips:
            nearest = min(
                (math.dist(tip, m) for hexagon in self.hexes for m in flat_midpoints(hexagon))
            )
            worst = nearest if worst is None else max(worst, nearest)
        self.assertLess(worst, 0.02, f"a star tip misses its flat midpoint by {worst:.3f} px")

    def test_the_hexagons_are_regular(self):
        for hexagon in self.hexes:
            sides = [math.dist(hexagon[i], hexagon[(i + 1) % 6]) for i in range(6)]
            self.assertLess(max(sides) - min(sides), 0.05, f"irregular hexagon: {sides}")

    # ---- claim 3: the ring overlaps, by an amount fixed by the fold count ----
    def test_the_ring_overlaps_by_cos_15_of_the_chord(self):
        apothem = min(math.dist(centroid(h), m) for h in self.hexes[:1] for m in flat_midpoints(h))
        span = 2 * apothem                              # flat-to-flat width of one hexagon
        centres = [centroid(h) for h in self.hexes]
        spacing = min(math.dist(centres[i], centres[(i + 1) % 12]) for i in range(12))

        self.assertAlmostEqual(span, CHORD, delta=0.02, msg="hexagon width must equal the tip chord")
        self.assertAlmostEqual(spacing, 180.0, delta=0.02)
        self.assertGreater(span, spacing, "the ring closing edge-to-edge would make the overlap test vacuous")
        self.assertAlmostEqual(span - spacing, OVERLAP, delta=0.02,
                               msg="overlap must be chord * (1 - cos(pi/12)), a function of the fold count")

        # overlap / side = sqrt(3) * (1 - cos(pi/12)), because a hexagon side is chord / sqrt(3)
        side = math.dist(self.hexes[0][0], self.hexes[0][1])
        self.assertAlmostEqual((span - spacing) / side,
                               math.sqrt(3) * (1 - math.cos(math.pi / 12)), delta=0.002)
        self.assertAlmostEqual((span - spacing) / side * 100, 5.90, delta=0.05)

    def test_the_overlap_is_not_a_drawing_error_but_a_property_of_the_fold_count(self):
        """Two constraints cannot both hold: tips-on-flats and an edge-to-edge ring.

        Tips on flat midpoints forces the hexagon width to the tip chord, `2R sin(pi/n)`.
        Twelve of them around one star forces the centre spacing to `2R cos(pi/n) sin(pi/n)`
        = `R sin(2pi/n)`. The ratio of the two is `1/cos(pi/n)`, so the overlap survives every
        choice of radius and scale — only n can change it, and it never reaches zero.
        """
        for n in (8, 10, 12, 16, 24):
            chord = 2 * R_TIP * math.sin(math.pi / n)
            spacing = 2 * R_TIP * math.cos(math.pi / n) * math.sin(math.pi / n)
            self.assertAlmostEqual(chord / spacing, 1 / math.cos(math.pi / n), places=12)
            self.assertGreater(chord - spacing, 0.0, f"n={n} would close, which is the thing being denied")

    # ---- the artefact is the generator's output, and it is on the wall ----
    def test_the_committed_svg_is_what_the_generator_writes(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "12-point-girih-star.svg"
            subprocess.run([sys.executable, str(GENERATOR), "--out", str(out)],
                           check=True, capture_output=True)
            self.assertEqual(out.read_bytes(), SVG.read_bytes(),
                             "the plate on the wall is not what the generator produces")

    def test_the_plate_is_exhibited_and_the_matrix_names_it(self):
        page = PAGE.read_text(encoding="utf-8")
        self.assertIn("12-point-girih-star.svg", page, "the wing page must show the plate")
        matrix = MATRIX.read_text(encoding="utf-8")
        self.assertIn("12-point star-and-hexagon girih", matrix,
                      "the gallery matrix must name the plate in Desi's Islamic cell")

    def test_the_wall_text_does_not_claim_an_exact_tiling(self):
        page = PAGE.read_text(encoding="utf-8")
        self.assertNotIn("bridge adjacent star tips with exact trigonometric precision", page,
                         "that sentence is false: the ring overlaps by 6.35 px")
        self.assertIn("6.35", page, "the page must carry the measured overlap, not just a correction")


if __name__ == "__main__":
    unittest.main()

#!/usr/bin/env python3
"""Tests for the item ledger — the register behind the human's daily report.

The three things that would make the report a lie, and are therefore pinned here:
  1. an item is derived from the run's changed paths, so a run that changed nothing is not an item;
  2. internal/external is decided by whether the work could have reached the world, not by which
     amigo did it or how it was described;
  3. a postponed or rejected item must carry a reason — an item filed as "postponed" with no
     reason is indistinguishable from one that was quietly dropped.
"""
import contextlib
import datetime as dt
import io
import json
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from channels import item_ledger as il  # noqa: E402


def make_run(root: Path, run_id: str, changed: list[str], report: str) -> Path:
    d = root / run_id
    d.mkdir(parents=True)
    (d / "result.json").write_text(json.dumps({
        "run_id": run_id, "status": "awaiting_review", "changed_paths": changed,
    }), encoding="utf-8")
    (d / "report.txt").write_text(report, encoding="utf-8")
    return d


class TestDerivation(unittest.TestCase):
    def test_a_run_that_changed_nothing_is_not_an_item(self):
        with tempfile.TemporaryDirectory() as t:
            d = make_run(Path(t), "20261006T082758Z-245fa706", [], "I did nothing.")
            self.assertEqual(il.run_to_items("desi", d), [])

    def test_a_run_that_changed_files_is_one_item(self):
        with tempfile.TemporaryDirectory() as t:
            d = make_run(Path(t), "20261006T082758Z-245fa706",
                         ["scripts/x.py", "tests/test_x.py"],
                         "I built the thing that was missing.")
            items = il.run_to_items("desi", d)
            self.assertEqual(len(items), 1)
            self.assertEqual(items[0]["amigo"], "desi")
            self.assertEqual(items[0]["filed_utc"], "2026-10-06T08:27:58Z")
            self.assertEqual(items[0]["state"] if "state" in items[0] else None, None)
            self.assertEqual(items[0]["source"], "derived")

    def test_declared_items_override_the_derivation(self):
        with tempfile.TemporaryDirectory() as t:
            d = make_run(Path(t), "20261006T082758Z-245fa706", ["a.py", "docs/index.html"],
                         "Two things got done.\n"
                         "ITEM: [internal] fixed the lander\n"
                         "ITEM: [external] published the magazine page\n")
            items = il.run_to_items("desi", d)
            self.assertEqual([i["title"] for i in items],
                             ["fixed the lander", "published the magazine page"])
            self.assertEqual([i["scope"] for i in items], ["internal", "external"])


class TestGeneratedOnlyRuns(unittest.TestCase):
    """A run whose only changed paths are generated indexes is not an item.

    Added 2026-10-11 from the W-drain measurement (`channels/reports/2026-10-11-why-w-does-not-
    drain.md`, cause 3): 51 of 244 waiting items were hand-edits to DO-NOT-EDIT indexes, and one
    path-signature appeared seven times. A reviewer opening such an item can only ever write the
    same sentence, which is how a queue stops being opened.
    """

    def _repo_with_generated(self, t: str) -> Path:
        root = Path(t)
        (root / "discussions").mkdir()
        (root / "discussions" / "README.md").write_text(
            "<!-- GENERATED by scripts/gen_index.py — DO NOT EDIT THIS FILE. -->\n"
            "# Discussions — index\n", encoding="utf-8")
        (root / "channels").mkdir()
        (root / "channels" / "reject-queue.md").write_text(
            "# The reject queue\n\nHand-maintained, not generated.\n", encoding="utf-8")
        return root

    def test_the_real_generated_indexes_are_recognised(self):
        for p in ("discussions/README.md", "scripts/README.md", "channels/agenda.md"):
            self.assertTrue(il.is_generated_path(p), p)
        self.assertFalse(il.is_generated_path("channels/reject-queue.md"))
        self.assertFalse(il.is_generated_path("scripts/item_ledger_nonexistent.py"))

    def test_a_generated_only_run_files_no_item(self):
        with tempfile.TemporaryDirectory() as t:
            root = self._repo_with_generated(t)
            d = make_run(root, "20260924T040334Z-aef2763f",
                         ["discussions/README.md"], "I regenerated two indexes.")
            self.assertEqual(il.run_to_items("gemini", d, repo=root), [])

    def test_a_run_that_also_touched_a_real_file_is_still_an_item(self):
        with tempfile.TemporaryDirectory() as t:
            root = self._repo_with_generated(t)
            d = make_run(root, "20260928T001014Z-37c20a9a",
                         ["discussions/README.md", "channels/reject-queue.md"],
                         "I reviewed the reject queue and rebuilt an index.")
            items = il.run_to_items("gemini", d, repo=root)
            self.assertEqual(len(items), 1)
            self.assertEqual(items[0]["paths"],
                             ["discussions/README.md", "channels/reject-queue.md"])

    def test_a_declared_item_survives_the_generated_filter(self):
        with tempfile.TemporaryDirectory() as t:
            root = self._repo_with_generated(t)
            d = make_run(root, "20261006T082758Z-245fa706", ["discussions/README.md"],
                         "One thing got done.\nITEM: [internal] fixed the index generator\n")
            items = il.run_to_items("desi", d, repo=root)
            self.assertEqual([i["title"] for i in items], ["fixed the index generator"])


